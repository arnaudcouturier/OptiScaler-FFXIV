int main()
{
    // ---- the reader's slots: the packed word the shader object carries
    {
        const ReaderSlots slots = Complete();
        CHECK(slots.Complete());
        CHECK(IsWaterReader(slots));

        const uint32_t packed = PackSlots(slots);
        CHECK(packed != 0);
        const ReaderSlots back = UnpackSlots(packed);
        CHECK_EQ(back.reflection, 8u);
        CHECK_EQ(back.vposition, 6u);
        CHECK_EQ(back.camera, 2u);
        CHECK(back.water);

        // Every slot D3D11 can bind round-trips, in every field, and no field reaches another's byte.
        for (uint32_t slot = 0; slot < 128; ++slot)
        {
            ReaderSlots probe;
            probe.reflection = uint8_t(slot);
            probe.vposition = uint8_t(127 - slot);
            probe.camera = uint8_t(slot % 14);
            probe.water = (slot & 1) != 0;
            const ReaderSlots answer = UnpackSlots(PackSlots(probe));
            CHECK_EQ(answer.reflection, probe.reflection);
            CHECK_EQ(answer.vposition, probe.vposition);
            CHECK_EQ(answer.camera, probe.camera);
            CHECK_EQ(answer.water, probe.water);
        }

        // A missing name is 0xFF in its field and 0 in the packed word, which is what a shader that was never stamped reads.
        const ReaderSlots empty = UnpackSlots(0);
        CHECK(empty.reflection == kSlotMissing && empty.vposition == kSlotMissing && empty.camera == kSlotMissing);
        CHECK(!empty.water);
        CHECK(!empty.Complete());
        CHECK(!IsWaterReader(empty));
        CHECK_EQ(PackSlots(ReaderSlots {}), 0u);

        // A reader that declares the map but is not a water surface: its draws are passed on, not refused.
        ReaderSlots notWater = Complete();
        notWater.water = false;
        CHECK(!IsWaterReader(notWater));
        CHECK(!notWater.water);

        // A water shader that declares the water anchor but misses the view-position buffer or the camera table is a candidate for a refusal
        // (the session's log says which), and never a pass with a guessed slot.
        ReaderSlots partial = Complete();
        partial.vposition = kSlotMissing;
        CHECK(!partial.Complete());
        CHECK(!IsWaterReader(partial));
        partial = Complete();
        partial.camera = kSlotMissing;
        CHECK(!partial.Complete());
        // A slot past the last one D3D11 can bind is the same as a missing one.
        partial = Complete();
        partial.camera = 14;
        CHECK(!partial.HasCamera());
        partial = Complete();
        partial.reflection = 128;
        CHECK(!partial.HasReflection());
    }

    // ---- the bytecode parse: the slots a compiled shader declares, the effect compiler's `.T` suffix, and the water anchor
    {
        // The names this parse looks for. A rename fails here first, before any session finds a shader unstamped.
        CHECK(std::string(kVPositionName) == "g_SamplerVPosition");
        CHECK(std::string(kCameraName) == "g_CameraParameter");
        CHECK(std::string(kWaveName) == "g_SamplerWaveMap");
        CHECK(std::string(kCausticsName) == "g_SamplerCaustics");
        CHECK(std::string(ext::ffxiv::engine::kNames[11].name) == "g_SamplerReflectionMap");

        // The shapes this pass is entered by in a capture: a water shader of the water material is a reader only while it declares the map *and*
        // one of the two anchors *and* the engine's own names for the view position and the camera table. It is the same set of four names a
        // capture's water draws carry, so a rename of any one of them is a session where the pass is never reached.
        const ReaderSlots capture = SlotsOfShader(Ssr_StampCapture_cso, sizeof Ssr_StampCapture_cso);
        CHECK_EQ(capture.reflection, 8u);
        CHECK_EQ(capture.vposition, 0u);
        CHECK_EQ(capture.camera, 2u);
        CHECK(capture.water); // the wave map at t4 and the caustics map at t6, the slots the captured harbour reads
        CHECK(capture.Complete());
        CHECK(IsWaterReader(capture));

        // A water anchor with a number the module does not know (`g_SamplerWaveMap1`): the parse asks for the exact name, so this shader is a
        // sampler of the map and not a surface this pass answers for. A rename to NumberedWaveMap0/1 in the game would land here, not in a session.
        const ReaderSlots numbered = SlotsOfShader(Ssr_StampWaveName1_cso, sizeof Ssr_StampWaveName1_cso);
        CHECK_EQ(numbered.reflection, 8u);
        CHECK_EQ(numbered.vposition, 0u);
        CHECK_EQ(numbered.camera, 2u);
        CHECK(!numbered.water);
        CHECK(numbered.Complete());
        CHECK(!IsWaterReader(numbered));

        // A real compiled water shader: the reflection map at t8, the view position at t0, the camera table at b2, and the wave map that says
        // this is the water material. These are the slots the shader's own register assignments name, so a parse that read the wrong column of the
        // reflection, or that mistook a texture for a constant buffer, lands somewhere else.
        const ReaderSlots water = SlotsOfShader(Ssr_StampWater_cso, sizeof Ssr_StampWater_cso);
        CHECK_EQ(water.reflection, 8u);
        CHECK_EQ(water.vposition, 0u);
        CHECK_EQ(water.camera, 2u);
        CHECK(water.water);
        CHECK(water.Complete());
        CHECK(IsWaterReader(water));
        CHECK(UnpackSlots(PackSlots(water)).reflection == water.reflection);
        CHECK(UnpackSlots(PackSlots(water)).vposition == water.vposition);
        CHECK(UnpackSlots(PackSlots(water)).camera == water.camera);
        CHECK(UnpackSlots(PackSlots(water)).water);
        CHECK(Mentions(Ssr_StampWater_cso, sizeof Ssr_StampWater_cso, "g_SamplerReflectionMap"));

        // The same declarations without the water anchors: a sampler of the map, and not a surface this pass answers for - so its draws are passed
        // on and not refused, which is what `water` is for.
        const ReaderSlots noWave = SlotsOfShader(Ssr_StampNoWave_cso, sizeof Ssr_StampNoWave_cso);
        CHECK_EQ(noWave.reflection, 8u);
        CHECK_EQ(noWave.vposition, 0u);
        CHECK_EQ(noWave.camera, 2u);
        CHECK(!noWave.water);
        CHECK(noWave.Complete());
        CHECK(!IsWaterReader(noWave));

        // Neither the map nor a water anchor: nothing to read, and the cheap byte scan already drops it before the reflection parse runs.
        const ReaderSlots noMap = SlotsOfShader(Ssr_StampNoMap_cso, sizeof Ssr_StampNoMap_cso);
        CHECK(!noMap.HasReflection());
        CHECK(!noMap.water);
        CHECK(!IsWaterReader(noMap));
        CHECK(!Mentions(Ssr_StampNoMap_cso, sizeof Ssr_StampNoMap_cso, "g_SamplerReflectionMap"));

        // The effect compiler's suffix: the engine's own reflection names a texture `g_SamplerVPosition.T` and its sampler `...S`, and it
        // writes the sampler FIRST, at its own register. fxc cannot produce that, so the suffix is checked on a blob built in the reflection's
        // own layout - with the caustics anchor instead of the wave map, which is the other of the two anchors a water shader may carry.
        const std::vector<uint8_t> suffixed = RdefBlob({ { "g_SamplerReflectionMap.S", 3, 1 },
                                                         { "g_SamplerVPosition.S", 3, 3 },
                                                         { "g_SamplerReflectionMap.T", 2, 4 },
                                                         { "g_SamplerVPosition.T", 2, 6 },
                                                         { "g_CameraParameter", 0, 2 },
                                                         { "g_SamplerCaustics.T", 2, 3 },
                                                         { "g_SamplerCaustics.S", 3, 5 } });
        const ReaderSlots fromSuffix = SlotsOfShader(suffixed.data(), suffixed.size());
        CHECK_EQ(fromSuffix.reflection, 4u); // the texture's slot; a name-only scan answers the sampler's 1
        CHECK_EQ(fromSuffix.vposition, 6u);  // the texture's slot; the sampler is at 3
        CHECK_EQ(fromSuffix.camera, 2u);
        CHECK(fromSuffix.water); // the caustics anchor, which the capture's family B declares too
        CHECK(IsWaterReader(fromSuffix));

        // The control: a pair whose sampler and texture share one register, which is the shape a wrong-type match survives. The answer is the
        // texture's slot either way, which is why the case above (the two numbers apart) is the one that says why the kind has to be checked.
        const std::vector<uint8_t> sameSlot = RdefBlob({ { "g_SamplerReflectionMap.S", 3, 4 },
                                                         { "g_SamplerReflectionMap.T", 2, 4 },
                                                         { "g_SamplerVPosition.S", 3, 6 },
                                                         { "g_SamplerVPosition.T", 2, 6 },
                                                         { "g_CameraParameter", 0, 2 },
                                                         { "g_SamplerWaveMap.T", 2, 9 },
                                                         { "g_SamplerWaveMap.S", 3, 9 } });
        const ReaderSlots fromSameSlot = SlotsOfShader(sameSlot.data(), sameSlot.size());
        CHECK_EQ(fromSameSlot.reflection, 4u);
        CHECK_EQ(fromSameSlot.vposition, 6u);
        CHECK_EQ(fromSameSlot.camera, 2u);
        CHECK(IsWaterReader(fromSameSlot));

        // A truncated or empty blob is no reader at all, never a stamp with guessed slots.
        CHECK(!SlotsOfShader(nullptr, 0).HasReflection());
        CHECK(!SlotsOfShader(suffixed.data(), 8).HasReflection());
        CHECK(!SlotsOfShader(suffixed.data(), 40).HasReflection());
    }

    // ---- the tuning: the ranges, the defaults and the identity rules
    {
        Params defaults;
        CHECK(!defaults.on);
        CHECK_EQ(defaults.steps, 48u);
        CHECK(Near(defaults.thickness, 0.3f));
        CHECK(Near(defaults.blend, 0.5f)); // the traced reflection mixed with the engine's own map, not a replacement of it
        CHECK(Near(defaults.fade, 0.15f));
        CHECK(IsIdentity(defaults)); // the key off is today's picture
        CHECK(!Wants(defaults));

        Params on = Tuned();
        CHECK(!IsIdentity(on));
        CHECK(Wants(on));

        // The steps: 16..128, a value out of range reads as its nearest end, a NaN as the default.
        CHECK_EQ(ClampSteps(16.0f), 16u);
        CHECK_EQ(ClampSteps(128.0f), 128u);
        CHECK_EQ(ClampSteps(1.0f), 16u);
        CHECK_EQ(ClampSteps(1000.0f), 128u);
        CHECK_EQ(ClampSteps(std::numeric_limits<float>::quiet_NaN()), 48u);
        CHECK_EQ(ClampSteps(48.7f), 48u); // the count is a whole number of taps, and truncation keeps the shader's loop bound honest

        // The thickness, the blend and the fade: their ends hold, and a NaN is the default.
        CHECK(Near(ClampThickness(0.001f), kMinThickness));
        CHECK(Near(ClampThickness(9.0f), kMaxThickness));
        CHECK(Near(ClampThickness(std::numeric_limits<float>::quiet_NaN()), kThicknessDefault));
        CHECK(Near(ClampBlend(-1.0f), 0.0f));
        CHECK(Near(ClampBlend(2.0f), 1.0f));
        CHECK(Near(ClampBlend(std::numeric_limits<float>::quiet_NaN()), 0.5f));
        CHECK(Near(ClampFade(-0.1f), 0.0f));
        CHECK(Near(ClampFade(0.75f), kMaxFade));
        CHECK(Near(ClampFade(std::numeric_limits<float>::quiet_NaN()), kFadeDefault));

        // A blend of 0 is today's picture even with the key on, and so is a NaN blend.
        on.blend = 0.0f;
        CHECK(IsIdentity(on));
        CHECK(!Wants(on));
        on = Tuned();
        on.blend = std::numeric_limits<float>::quiet_NaN();
        CHECK(IsIdentity(on));
    }

    // ---- what the card reads as armed: this module's own key, with the engine pass overrides' master key out of the picture
    {
        // The combinations of the switches that reach this card: only this module's own key arms it, because the seam is entered while any
        // feature wants a draw and this module's own switch is one of them. The engine pass overrides' master key is not an input here, so a
        // session with that master off and this card on reads armed - and, since the seam's feature bit asks every feature, it serves its draws.
        const Params tuned = Tuned();
        CHECK(!CardArmed(/*key*/ false, tuned, /*sessionArmed*/ true));
        CHECK(CardArmed(/*key*/ true, tuned, /*sessionArmed*/ true));

        // A blend at zero or a stood-down session reads off, and so does a key that is off whatever the parameters say.
        Params zeroBlend = tuned;
        zeroBlend.blend = 0.0f;
        CHECK(!CardArmed(/*key*/ true, zeroBlend, /*sessionArmed*/ true));
        CHECK(!CardArmed(/*key*/ true, tuned, /*sessionArmed*/ false));
        Params off = tuned;
        off.on = false;
        CHECK(!CardArmed(/*key*/ true, off, /*sessionArmed*/ true));
    }

    // ---- which texture under the reflection name is the planar map
    {
        CHECK(IsPlanarTarget(kPlanarFormat, 1920, 1080));
        CHECK(IsPlanarTarget(kPlanarFormat, 16, 16));
        CHECK(!IsPlanarTarget(kPlanarFormat, 8, 8));            // a few texels: something else's texture under the name
        CHECK(!IsPlanarTarget(28u, 1920, 1080));                // R8G8B8A8: not the engine's planar map
        CHECK(!IsPlanarTarget(kSceneFormat, 1920, 1080));       // a half-float target is the scene, not the map

        // A typeless resource is its typed sibling: a copy between them and a shader load of either are the same data, so a build that gives the map
        // or the scene a typeless resource is served instead of being refused for a format mismatch that is not one.
        CHECK(AcceptFormat(kPlanarFormat, kPlanarFormat));
        CHECK(AcceptFormat(kPlanarTypelessFormat, kPlanarFormat));
        CHECK(AcceptFormat(kSceneFormat, kSceneFormat));
        CHECK(AcceptFormat(kSceneTypelessFormat, kSceneFormat));
        CHECK(AcceptFormat(kSceneTypelessFormat, kVPositionFormat)); // the scene and the view position are the same half-float allocation
        CHECK(!AcceptFormat(kPlanarFormat, kSceneFormat));           // the map is not the scene, typeless or not
        CHECK(!AcceptFormat(28u, kPlanarFormat));                    // R8G8B8A8 is neither of them
        ReaderFacts typeless = Good();
        typeless.planarFormat = kPlanarTypelessFormat;
        typeless.sceneFormat = kSceneTypelessFormat;
        typeless.vpositionFormat = kSceneTypelessFormat;
        CHECK(Classify(typeless) == Decline::None);
    }

    // ---- the validation: one reason at a time
    {
        const ReaderFacts good = Good();
        CHECK(Classify(good) == Decline::None);

        ReaderFacts facts = good;
        facts.replay = true;
        CHECK(Classify(facts) == Decline::Replay);

        facts = good;
        facts.hasPlanar = false;
        CHECK(Classify(facts) == Decline::NoPlanar);

        facts = good;
        facts.planarFormat = 28;
        CHECK(Classify(facts) == Decline::PlanarShape);

        facts = good;
        facts.planarWidth = 4;
        facts.planarHeight = 4;
        CHECK(Classify(facts) == Decline::PlanarShape); // the engine's placeholder, which is another draw of the frame

        facts = good;
        facts.planarSamples = 4;
        CHECK(Classify(facts) == Decline::PlanarShape);

        facts = good;
        facts.hasScene = false;
        CHECK(Classify(facts) == Decline::NoScene);

        facts = good;
        facts.sceneFormat = 28;
        CHECK(Classify(facts) == Decline::NoScene); // a scene target this pass cannot copy into its own half-float one

        facts = good;
        facts.sceneSamples = 2;
        CHECK(Classify(facts) == Decline::NoScene);

        facts = good;
        facts.hasVPosition = false;
        CHECK(Classify(facts) == Decline::NoVPosition);

        facts = good;
        facts.vpositionFormat = 11;
        CHECK(Classify(facts) == Decline::NoVPosition);

        facts = good;
        facts.vpositionSamples = 2;
        CHECK(Classify(facts) == Decline::NoVPosition);

        facts = good;
        facts.hasCamera = false;
        CHECK(Classify(facts) == Decline::NoCamera);

        facts = good;
        facts.cameraBytes = kCameraBytes - 16;
        CHECK(Classify(facts) == Decline::NoCamera);

        facts = good;
        facts.vpositionWidth = 1920;
        CHECK(Classify(facts) == Decline::SizeMismatch); // not the scene's allocation

        facts = good;
        facts.window[2] = 8.0f;
        CHECK(Classify(facts) == Decline::SizeMismatch); // a few texels of picture is a preview, not a scene

        facts = good;
        facts.window[0] = -1.0f;
        CHECK(Classify(facts) == Decline::SizeMismatch);

        facts = good;
        facts.window[0] = 0.0f;
        facts.window[2] = 3841.0f;
        CHECK(Classify(facts) == Decline::SizeMismatch); // past the allocation

        // Half a pixel of slack: the engine's +0.5 origin lands on the edge and is still the window.
        facts = good;
        facts.window[0] = 0.5f;
        facts.window[2] = 1920.0f;
        CHECK(Classify(facts) == Decline::None);

        // The slack is exactly half a texel at the allocation's own edge: a window of the allocation's width starting at 0.5 ends at 3840.5 and
        // is the picture, and half a texel more is past it. The bound is what makes the engine's +0.5 viewport origin a valid full-size window
        // rather than a refusal, so it is tested at the edge and not only in the middle of the allocation.
        facts = good;
        facts.window[0] = 0.5f;
        facts.window[2] = 3840.0f;
        CHECK(Classify(facts) == Decline::None);
        facts = good;
        facts.window[0] = 0.5f;
        facts.window[2] = 3840.5f;
        CHECK(Classify(facts) == Decline::SizeMismatch);
        facts = good;
        facts.window[1] = 0.5f;
        facts.window[3] = 2160.0f;
        CHECK(Classify(facts) == Decline::None);
        facts = good;
        facts.window[1] = 0.5f;
        facts.window[3] = 2160.5f;
        CHECK(Classify(facts) == Decline::SizeMismatch);

        // A window that covers no whole texel of the planar map leaves nothing this module can align to the engine's answer.
        facts = good;
        facts.window[0] = 3839.0f;
        facts.window[1] = 2159.0f;
        facts.window[2] = 1.0f;
        facts.window[3] = 1.0f;
        CHECK(Classify(facts) == Decline::SizeMismatch);
    }

    // ---- the mapping and the region: the ambient occlusion pass's own rule, fed this pass's three numbers
    {
        const ReaderFacts good = Good();
        const ao::Mapping mapping = MappingOf(good);
        CHECK(Near(mapping.scaleX, 2.0f));
        CHECK(Near(mapping.scaleY, 2.0f));

        // The session's shape: the picture is 1920x1080 inside a 3840x2160 allocation, so our 1920x1080 map answers for its 960x540 quadrant -
        // the part the engine's own producer fills.
        const ao::Region region = RegionOf(good);
        CHECK_EQ(region.x, 0u);
        CHECK_EQ(region.y, 0u);
        CHECK_EQ(region.width, 960u);
        CHECK_EQ(region.height, 540u);

        // The picture at the allocation's own size: the whole map, and no ratio.
        ReaderFacts same = good;
        same.sceneWidth = same.vpositionWidth = 1920;
        same.sceneHeight = same.vpositionHeight = 1080;
        const ao::Mapping flat = MappingOf(same);
        CHECK(Near(flat.scaleX, 1.0f));
        const ao::Region whole = RegionOf(same);
        CHECK_EQ(whole.width, 1920u);
        CHECK_EQ(whole.height, 1080u);

        // A window at an offset: the region starts at the block that lies wholly inside it.
        ReaderFacts offset = good;
        offset.window[0] = 64.0f;
        offset.window[1] = 32.0f;
        offset.window[2] = 1856.0f;
        offset.window[3] = 1048.0f;
        const ao::Region shifted = RegionOf(offset);
        CHECK_EQ(shifted.x, 32u);
        CHECK_EQ(shifted.y, 16u);
        CHECK_EQ(shifted.width, 928u);
        CHECK_EQ(shifted.height, 524u);
    }

    // ---- the shader's 80-byte constant block
    {
        const ReaderFacts good = Good();
        const Params params = Tuned();
        const Constants constants = ConstantsOf(good, params);
        static_assert(sizeof(Constants) == 80, "five float4s");
        CHECK(Near(constants.window[0], 0.0f));
        CHECK(Near(constants.window[2], 1920.0f));
        CHECK(Near(constants.mapping[0], 2.0f));
        CHECK(Near(constants.mapping[2], 1920.0f)); // the planar target's width
        CHECK(Near(constants.mapping[3], 1080.0f));
        CHECK(Near(constants.sizes[0], 3840.0f)); // the scene allocation
        CHECK(Near(constants.sizes[2], 48.0f));
        CHECK(Near(constants.sizes[3], 0.3f));
        CHECK(Near(constants.tuning[0], kBlendDefault)); // the blend: the default mixes the traced reflection with the engine's own map
        CHECK(Near(constants.tuning[0], 0.5f));
        CHECK(Near(constants.tuning[1], 0.15f)); // the fade
        CHECK(Near(constants.tuning[2], kConfidenceThreshold));
        CHECK(Near(constants.tuning[3], kSelfGrazeMetres)); // the self-graze distance rides the block for the shader's rejection
        CHECK(Near(constants.region[0], 0.0f));
        CHECK(Near(constants.region[2], 960.0f));
        CHECK(Near(constants.region[3], 540.0f));

        // The tuning reaches the block unchanged, so the shader's picture cannot drift from the key the card shows.
        Params moved;
        moved.on = true;
        moved.steps = 96;
        moved.thickness = 1.5f;
        moved.blend = 0.25f;
        moved.fade = 0.4f;
        const Constants retuned = ConstantsOf(good, moved);
        CHECK(Near(retuned.sizes[2], 96.0f));
        CHECK(Near(retuned.sizes[3], 1.5f));
        CHECK(Near(retuned.tuning[0], 0.25f));
        CHECK(Near(retuned.tuning[1], 0.4f));

        // LIVE1 item 3 (the first rc7c session): the saved INI said blend 1.0 / fade 0.0 and the first RunFrame line said blend 0.50 / fade 0.15. The
        // 0.50 / 0.15 were this module's DEFAULTS (the keys were `auto` at launch); the user then dragged both sliders in the menu (fade 0.14 -> 0.50
        // -> 0.01 at 11:33:27-29, blend 0.40 -> ... -> 1.00 at 11:33:30-32), and 147 of the 226 RunFrame lines read blend 1.00. Nothing caps the
        // weight below the keys: the keys' ends reach the shader's block unchanged, and the shader's weight is saturate(blend x confidence) with
        // confidence = saturate(edge / max(fade, 1e-4)) (tests/ext/ffxiv/engine/ssr_warp.cpp runs that formula against the real shader on WARP).
        CHECK(Near(kBlendDefault, 0.5f) && Near(kFadeDefault, 0.15f));
        CHECK(Near(ClampBlend(1.0f), 1.0f) && Near(ClampFade(0.0f), 0.0f) && Near(ClampFade(0.5f), 0.5f) && Near(ClampBlend(0.0f), 0.0f));
        Params end;
        end.on = true;
        end.blend = ClampBlend(1.0f);
        end.fade = ClampFade(0.0f);
        const Constants endBlock = ConstantsOf(good, end);
        CHECK(Near(endBlock.tuning[0], 1.0f) && Near(endBlock.tuning[1], 0.0f));
        CHECK(!IsIdentity(end));
        Params engineOnly = end;
        engineOnly.blend = 0.0f;
        CHECK(IsIdentity(engineOnly)); // a blend of zero is the engine's own map and runs nothing
    }

    // ---- the per-frame memory: one attempt, one texture, forgotten by the next frame
    {
        FrameCache cache;
        CHECK(cache.MayRun()); // no frame read yet
        cache.Begin(7);
        CHECK(cache.MayRun());
        CHECK(!cache.Has(reinterpret_cast<const void*>(0x1000)));

        cache.TakeAttempt();
        CHECK(!cache.MayRun()); // the frame's one attempt is spent
        cache.Record(reinterpret_cast<const void*>(0x1000), reinterpret_cast<const void*>(0x1000), reinterpret_cast<const void*>(0x2000));
        CHECK(cache.Has(reinterpret_cast<const void*>(0x1000)));
        CHECK(!cache.Has(reinterpret_cast<const void*>(0x1001))); // the engine's other texture is another binding
        CHECK(cache.Ours() == reinterpret_cast<const void*>(0x2000));

        // The next frame forgets the entry and gives the attempt back.
        cache.Begin(8);
        CHECK(!cache.Has(reinterpret_cast<const void*>(0x1000)));
        CHECK(cache.MayRun());
        CHECK(cache.Ours() == nullptr);

        // A token that does not advance expires after the serve budget, so a stale texture cannot answer for a session.
        cache.Begin(9);
        cache.Record(reinterpret_cast<const void*>(0x3000), reinterpret_cast<const void*>(0x3000), reinterpret_cast<const void*>(0x4000));
        for (uint32_t i = 0; i < kMaxServedDraws; ++i)
            cache.Serve();
        CHECK(!cache.Has(reinterpret_cast<const void*>(0x3000)));
        CHECK(cache.MayRun()); // and the next draw patches again instead of binding the old texture

        cache.Reset();
        CHECK(cache.Ours() == nullptr && !cache.Has(reinterpret_cast<const void*>(0x3000)));
    }

    // ---- the gate of one water draw: a replay is passed on before the frame's one attempt, so a preview is never served the frame's texture
    {
        FrameCache cache;
        cache.Begin(7);
        CHECK(ServeAnswer(cache, /*replay*/ false) == Serve::Attempt); // the frame's own first water draw runs the pass
        // A replay of a game draw costs the frame nothing: the answer is a pass-on and the frame's memory is exactly as it was, so the frame's own
        // reader still gets its attempt.
        CHECK(ServeAnswer(cache, /*replay*/ true) == Serve::PassOn);
        CHECK(cache.MayRun());
        CHECK(!cache.valid); // the frame's entry is untouched: still no result, so the next water draw still runs the pass

        cache.TakeAttempt();
        CHECK(ServeAnswer(cache, /*replay*/ false) == Serve::PassOn); // the one attempt is spent, and a later draw does not retry
        CHECK(ServeAnswer(cache, /*replay*/ true) == Serve::PassOn);

        cache.Record(reinterpret_cast<const void*>(0x1000), reinterpret_cast<const void*>(0x1000), reinterpret_cast<const void*>(0x2000));
        CHECK(ServeAnswer(cache, /*replay*/ false) == Serve::Serve); // the frame's texture answers every later water draw
        CHECK(ServeAnswer(cache, /*replay*/ true) == Serve::PassOn); // and the replay is passed on even while one exists
    }

    // ---- the scene copy's box: the window's own texels, floored and clamped to the allocation
    {
        // The captured session's window: 1920x1080 at the origin of a 3840x2160 allocation, copied as it is.
        const SceneCopy whole = SceneCopyOf(Good());
        CHECK_EQ(whole.x, 0u);
        CHECK_EQ(whole.y, 0u);
        CHECK_EQ(whole.width, 1920u);
        CHECK_EQ(whole.height, 1080u);

        // A fractional window (a render scale that does not land on a texel) asks for the texel it covers part of.
        ReaderFacts fractional = Good();
        fractional.window[2] = 1920.5f;
        fractional.window[3] = 1080.25f;
        CHECK(Classify(fractional) == Decline::None); // still the frame's window: half a texel of slack is allowed
        const SceneCopy rounded = SceneCopyOf(fractional);
        CHECK_EQ(rounded.width, 1921u);
        CHECK_EQ(rounded.height, 1081u);

        // At the allocation's own edge the same rounding asks for one texel past it: the slack Classify allows lets the window reach 3840.5, and a
        // copy box whose right edge is 3841 is an out-of-bounds copy rather than a fail-open. The rule clamps it to the allocation.
        ReaderFacts edge = Good();
        edge.window[2] = 3840.5f;
        edge.window[3] = 2160.5f;
        CHECK(Classify(edge) == Decline::None);
        const SceneCopy clamped = SceneCopyOf(edge);
        CHECK_EQ(clamped.width, 3840u);
        CHECK_EQ(clamped.height, 2160u);

        // An offset window is clamped against the room the origin leaves, and a window with no room at all copies nothing (the caller refuses).
        ReaderFacts offset = Good();
        offset.window[0] = 1920.0f;
        offset.window[1] = 1080.0f;
        offset.window[2] = 1920.5f;
        offset.window[3] = 1080.5f;
        CHECK(Classify(offset) == Decline::None);
        const SceneCopy right = SceneCopyOf(offset);
        CHECK_EQ(right.x, 1920u);
        CHECK_EQ(right.y, 1080u);
        CHECK_EQ(right.width, 1920u);
        CHECK_EQ(right.height, 1080u);

        ReaderFacts none = Good();
        none.window[0] = 3840.0f;
        none.window[1] = 2160.0f;
        none.window[2] = 16.0f;
        none.window[3] = 16.0f;
        const SceneCopy empty = SceneCopyOf(none);
        CHECK_EQ(empty.width, 0u);
        CHECK_EQ(empty.height, 0u);
    }

    // ---- the session: sixty-four refusals in a row switch the module off, a run starts the count over
    {
        Session session;
        CHECK(session.Armed());
        for (uint32_t i = 0; i + 1 < kDeclineLimit; ++i)
            CHECK(!session.NoteDecline());
        CHECK(session.Armed());
        CHECK(session.NoteDecline()); // the sixty-fourth
        CHECK(!session.Armed());
        CHECK(!session.NoteDecline()); // and it stays off: no second line

        Session again;
        for (uint32_t i = 0; i < 10; ++i)
            again.NoteDecline();
        again.NoteRun(); // one served frame
        for (uint32_t i = 0; i + 1 < kDeclineLimit; ++i)
            CHECK(!again.NoteDecline());
        CHECK(again.Armed());
    }

    // ---- the log: one line per change of state, and a budget
    {
        LogGate gate;
        CHECK(gate.Take(1));
        CHECK(!gate.Take(1)); // the same state again is not a new line
        CHECK(gate.Take(2));
        unsigned taken = 0;
        for (uint32_t i = 0; i < kMaxLogLines + 10; ++i)
            if (gate.Take(100 + i))
                ++taken;
        CHECK_EQ(taken + 2u, kMaxLogLines); // the two lines above, then the budget: one line per state and never more than the budget
        CHECK(!gate.Take(100 + kMaxLogLines + 10));

        // The lines a session reads: the refusal names its reason and what the draw bound, the run says what the pass computes, the served line
        // says how many readers a frame answered, and the switch-off line names the limit.
        const std::string refused = FormatRefusedReader(Decline::NoScene, Good(), Complete());
        CHECK(refused.find("the draw writes no scene target") != std::string::npos);
        CHECK(refused.find("planar 1920x1080") != std::string::npos);
        CHECK(refused.find("view position 3840x2160 at slot 6") != std::string::npos);
        CHECK(refused.find("camera 352 bytes at slot 2") != std::string::npos);
        CHECK(refused.find("slot 2") != std::string::npos);

        // A slot that is not there reads as "none" instead of a number nobody can act on.
        ReaderSlots missing = Complete();
        missing.vposition = kSlotMissing;
        CHECK(FormatRefusedReader(Decline::NoVPosition, Good(), missing).find("at slot none") != std::string::npos);

        const std::string run = FormatRun(Tuned(), 1920, 1080, false, 0.0);
        CHECK(run.find("1920x1080 at 48 steps") != std::string::npos);
        CHECK(run.find("thickness 0.30 m") != std::string::npos);
        CHECK(run.find("blend 0.50") != std::string::npos);
        CHECK(run.find("fade 0.15") != std::string::npos);
        CHECK(run.find("not measured yet") != std::string::npos);
        CHECK(FormatRun(Tuned(), 1920, 1080, true, 0.4321).find("0.4321 ms") != std::string::npos);

        // The run line waits for the first timestamp pair: a line written on the run that began the pair would always say "not measured yet",
        // and nothing later would print the figure. Only a pass that can never measure writes the clause on its first run.
        CHECK(!RunLineDue(/*logged*/ false, /*measured*/ false, /*canMeasure*/ true));
        CHECK(RunLineDue(/*logged*/ false, /*measured*/ true, /*canMeasure*/ true));
        CHECK(RunLineDue(/*logged*/ false, /*measured*/ false, /*canMeasure*/ false));
        CHECK(!RunLineDue(/*logged*/ true, /*measured*/ true, /*canMeasure*/ true)); // one line a session

        // The card's own line carries the measured cost once it lands, and says nothing extra before that.
        CHECK(FormatGpuCost(/*have*/ false, 0.0).empty());
        CHECK(FormatGpuCost(/*have*/ true, 0.4321).find("0.432 ms on the GPU") != std::string::npos);

        CHECK(FormatServed(22u).find("22 water draws") != std::string::npos);
        CHECK(FormatSwitchedOff().find("64 water draws in a row") != std::string::npos);
        CHECK(FormatDecline(Decline::PlanarShape).find("not the engine's planar reflection map") != std::string::npos);
    }

    // ---- the passed-on reasons: twelve stops that are not refusals, one line each a session, and a card that shows them
    {
        CHECK_EQ(kPassedOnCount, 12u);
        CHECK_EQ(uint32_t(PassedOn::NotReflection), 0u);
        CHECK_EQ(uint32_t(PassedOn::NoSlot) + 1, kPassedOnCount);
        // Every reason has its own name, and none of them is the empty string or "unknown": a capture's line is the only place a session reads
        // why the water draws were passed on.
        for (uint32_t i = 0; i < kPassedOnCount; ++i)
        {
            const char* name = PassedOnName(PassedOn(i));
            CHECK(name != nullptr && *name != '\0');
            CHECK(std::string(name) != "unknown");
            for (uint32_t j = i + 1; j < kPassedOnCount; ++j)
                CHECK(std::string(name) != PassedOnName(PassedOn(j)));
        }

        // One line per reason per session, out of the module's own budget: a second draw of the same reason writes nothing, and two reasons that
        // alternate do not each spend a line every time they alternate.
        PassedOnGate gate;
        LogGate budget;
        CHECK(gate.Take(PassedOn::NoStamp, budget));
        CHECK(!gate.Take(PassedOn::NoStamp, budget));
        CHECK(gate.Take(PassedOn::NotArmed, budget));
        CHECK(!gate.Take(PassedOn::NoStamp, budget));
        CHECK_EQ(budget.lines, 2u);

        // The line says the draw was not refused, and names the shader's bytecode when the draw's shader is at hand.
        const std::string plain = FormatPassedOn(PassedOn::NoStamp, 0u);
        CHECK(plain.find("not a refusal") != std::string::npos);
        CHECK(plain.find(PassedOnName(PassedOn::NoStamp)) != std::string::npos);
        CHECK(plain.find("0x") == std::string::npos);
        const std::string named = FormatPassedOn(PassedOn::NoStamp, 0x9C6B0836u);
        CHECK(named.find("0x9c6b0836") != std::string::npos); // the CRC a capture's draws.csv names the same shader by

        // The read binding of a water draw the gate passed on: the stamp's word, the map slot it names, the slot the draw path read, and the view
        // that was bound there. This is the fact a session could not read before, and the capture and the log print the same words.
        {
            ReaderSlots slots = Complete(); // map 8, view position 6, camera 2, water
            ReadBinding read;
            read.have = true;
            read.stamp = PackSlots(slots);
            read.slot = slots.reflection;
            read.view = 4; // D3D11_SRV_DIMENSION_TEXTURE2D
            read.array = 1;
            read.format = kSceneFormat; // the view position at t0 is the half-float scene allocation
            read.width = 3840;
            read.height = 2160;
            read.texture = 0x1e6b8cdeee0ull;
            const std::string readText = FormatReadBinding(read);
            CHECK(readText.find("stamp 0x01030709") != std::string::npos); // map 8 (9), view 6 (7), camera 2 (3), water
            CHECK(readText.find("map slot 8") != std::string::npos);
            CHECK(readText.find("read slot 8") != std::string::npos);
            CHECK(readText.find("view TEXTURE2D") != std::string::npos);
            CHECK(readText.find("array 1") != std::string::npos);
            CHECK(readText.find("format R16G16B16A16_FLOAT") != std::string::npos);
            CHECK(readText.find("3840x2160") != std::string::npos);
            CHECK(readText.find("texture 1e6b8cdeee0") != std::string::npos);

            // The log line carries the same facts after the CRC, and neither of them appears when the draw read no slot.
            const std::string detailed = FormatPassedOn(PassedOn::OtherMap, 0x60F6192Cu, &read);
            CHECK(detailed.find(PassedOnName(PassedOn::OtherMap)) != std::string::npos);
            CHECK(detailed.find("0x60f6192c") != std::string::npos);
            CHECK(detailed.find("the read binding was " + readText) != std::string::npos);
            CHECK(FormatPassedOn(PassedOn::OtherMap, 0x60F6192Cu).find("read binding") == std::string::npos);
            ReadBinding absent;
            CHECK(FormatReadBinding(absent) == "-");
            CHECK(FormatPassedOn(PassedOn::OtherMap, 0u, &absent).find("read binding") == std::string::npos);

            // The names a value this build does not know prints: its number, never a guess.
            CHECK(SrvDimensionText(5) == "TEXTURE2DARRAY");
            CHECK(SrvDimensionText(99) == "view 99");
            CHECK(SrvFormatText(kPlanarFormat) == "B8G8R8A8_UNORM");
            CHECK(SrvFormatText(12345) == "format 12345");
        }

        // The card's second line: only the reasons that happened, in the enum's own order.
        uint32_t counts[kPassedOnCount] {};
        CHECK(FormatPassedOnCounts(counts).empty());
        counts[uint32_t(PassedOn::NoStamp)] = 3;
        counts[uint32_t(PassedOn::NotArmed)] = 12;
        const std::string shown = FormatPassedOnCounts(counts);
        CHECK(shown.find(PassedOnName(PassedOn::NoStamp)) != std::string::npos);
        CHECK(shown.find(" 3") != std::string::npos);
        CHECK(shown.find(" 12") != std::string::npos);
        CHECK(shown.find(PassedOnName(PassedOn::NotArmed)) < shown.find(PassedOnName(PassedOn::NoStamp)));
        for (uint32_t i = 0; i < kPassedOnCount; ++i)
            if (i != uint32_t(PassedOn::NoStamp) && i != uint32_t(PassedOn::NotArmed))
                CHECK(shown.find(PassedOnName(PassedOn(i))) == std::string::npos);

        // The card's own transition line: the state it is publishing, and the blend a card at "on" can still be running nothing with.
        CHECK(FormatPublish(/*armed*/ true, 1.0f).find("the card is on, blend 1.00") != std::string::npos);
        CHECK(FormatPublish(/*armed*/ false, 0.0f).find("the card is off or at blend 0.00") != std::string::npos);
    }

    // ---- the name this pass must find in the shared table, and the anchor the draw path is entered by
    {
        CHECK(ext::ffxiv::engine::kNameCount == 20u); // the chara family's own g_AmbientParam row (the lighting tab's knob) joined after the material family's fog buffer
        CHECK(std::string(ext::ffxiv::engine::kNames[11].name) == "g_SamplerReflectionMap");
        CHECK(ext::ffxiv::engine::kNames[11].kind == ext::ffxiv::engine::NameKind::Texture);

        // A reader of the map is what the shared rule classifies; every other draw of the frame is passed on at that bit test.
        ext::ffxiv::engine::PassLayout layout;
        layout.ok = true;
        layout.found = 1u << 11;
        layout.slots[11] = 8;
        CHECK(ext::ffxiv::engine::IsReflectionDraw(layout));
        const ext::ffxiv::engine::Anchors anchors = ext::ffxiv::engine::DrawAnchors(layout);
        CHECK(ext::ffxiv::engine::IsReflectionAnchors(anchors));
        CHECK_EQ(anchors & ext::ffxiv::engine::kReflectionReaderBit, ext::ffxiv::engine::kReflectionReaderBit);
        CHECK_EQ(anchors & ~ext::ffxiv::engine::kReflectionReaderBit, 0ull); // no slot field: the shader object carries the slot

        layout.slots[11] = 128; // a slot D3D11 does not expose: not a reader this module can serve
        CHECK(!ext::ffxiv::engine::IsReflectionDraw(layout));
        CHECK_EQ(ext::ffxiv::engine::DrawAnchors(layout), 0ull);

        ext::ffxiv::engine::PassLayout other;
        other.ok = true;
        other.found = 1u << 0;
        other.slots[0] = 1;
        CHECK(!ext::ffxiv::engine::IsReflectionDraw(other));
        CHECK(!ext::ffxiv::engine::IsReflectionAnchors(ext::ffxiv::engine::DrawAnchors(other)));
    }

    // ---- replace, not add: the engine's own hit, the term's factor, the filter's weights ------------------------------------------------------------------
    {
        // An engine alpha above zero is the engine's own hit - in the 8-bit map the smallest level, 1/255, is one - and nothing else is.
        CHECK(!EngineHit(0.0f));
        CHECK(EngineHit(1.0f / 255.0f));
        CHECK(EngineHit(0.5f) && EngineHit(1.0f));
        CHECK(!EngineHit(-0.0f));
        CHECK_EQ(kEngineHitAlpha, 0.0f);

        // The factor a hit is written with is the blend times the confidence, in [0, 1]: it is both the alpha and the premultiplier of the colour.
        CHECK(Near(TermFactor(1.0f, 1.0f), 1.0f));
        CHECK(Near(TermFactor(0.5f, 1.0f), 0.5f));
        CHECK(Near(TermFactor(0.5f, 0.4f), 0.2f));
        CHECK(Near(TermFactor(1.0f, 0.0f), 0.0f));
        CHECK(Near(TermFactor(2.0f, 1.0f), 1.0f)); // never above 1
        CHECK(Near(TermFactor(-1.0f, 1.0f), 0.0f)); // never below 0

        // The owned targets' formats: the raw term is half-float rgba (premultiplied rgb and alpha), its guide a half-float distance.
        CHECK_EQ(kRawFormat, 10u);
        CHECK_EQ(kGuideFormat, 54u);

        // The filter: radius 2 (25 taps), the spatial weight falls as 1 / (1 + d^2), the guide's weight is 1 for equal hits and 0 once the hits
        // differ by the tolerance (relative to the farther one, with a floor so that two hits a few centimetres apart are always the same object).
        CHECK_EQ(kFilterRadius, 2);
        CHECK(Near(FilterSpatialWeight(0, 0), 1.0f));
        CHECK(Near(FilterSpatialWeight(1, 0), 0.5f) && Near(FilterSpatialWeight(0, -1), 0.5f));
        CHECK(Near(FilterSpatialWeight(1, 1), 1.0f / 3.0f));
        CHECK(Near(FilterSpatialWeight(2, 2), 1.0f / 9.0f));
        CHECK(FilterSpatialWeight(1, 0) > FilterSpatialWeight(1, 1) && FilterSpatialWeight(1, 1) > FilterSpatialWeight(2, 0));
        CHECK(Near(FilterGuideWeight(5.0f, 5.0f), 1.0f));
        CHECK(Near(FilterGuideWeight(5.0f, 4.5f), 1.0f - 0.5f / (5.0f * kGuideTolerance), 1e-4f)); // 10 % apart: a third of the weight left
        CHECK(FilterGuideWeight(5.0f, 3.0f) == 0.0f);                    // far beyond the tolerance
        CHECK(FilterGuideWeight(5.0f, 5.0f * (1.0f - kGuideTolerance) - 0.01f) == 0.0f); // just past it
        CHECK(FilterGuideWeight(5.0f, 4.0f) == 0.0f);                              // 20 % apart
        CHECK(Near(FilterGuideWeight(5.0f, 6.0f), FilterGuideWeight(6.0f, 5.0f))); // symmetric
        CHECK(FilterGuideWeight(10.0f, 9.5f) > FilterGuideWeight(10.0f, 9.0f));  // monotone in the difference
        // Near the origin the tolerance does not get tighter than kGuideFloor x kGuideTolerance: 0.2 m and 0.21 m are the same object.
        CHECK(Near(FilterGuideWeight(0.20f, 0.21f), 1.0f - 0.01f / (kGuideFloor * kGuideTolerance), 1e-4f));
        CHECK(FilterGuideWeight(0.01f, 0.20f) == 0.0f);
        CHECK_EQ(kGuideTolerance, 0.15f);
        CHECK_EQ(kGuideFloor, 0.25f);
    }

    return Finish("ssr_rules");
}
