// A water draw that passes every rule: the shape measured in a session (a 1920x1080 planar map inside a 3840x2160 allocation, the render window
// at the +0.5 origin the engine uses, the view-position buffer at the allocation's size and the camera table at its full size).
ReaderFacts Good()
{
    ReaderFacts facts;
    facts.hasPlanar = true;
    facts.hasScene = true;
    facts.hasVPosition = true;
    facts.hasCamera = true;
    facts.planarFormat = kPlanarFormat;
    facts.planarWidth = 1920;
    facts.planarHeight = 1080;
    facts.planarSamples = 1;
    facts.sceneFormat = kSceneFormat;
    facts.sceneWidth = 3840;
    facts.sceneHeight = 2160;
    facts.sceneSamples = 1;
    facts.vpositionFormat = kVPositionFormat;
    facts.vpositionWidth = 3840;
    facts.vpositionHeight = 2160;
    facts.vpositionSamples = 1;
    facts.cameraBytes = kCameraBytes;
    // The seam floors the viewport's +0.5 origin before it fills these (a texel grid has no half pixel), so a reader of the product carries 0.
    facts.window[0] = 0.0f;
    facts.window[1] = 0.0f;
    facts.window[2] = 1920.0f;
    facts.window[3] = 1080.0f;
    return facts;
}

Params Tuned()
{
    Params params;
    params.on = true;
    return params;
}

ReaderSlots Complete()
{
    ReaderSlots slots;
    slots.reflection = 8;
    slots.vposition = 6;
    slots.camera = 2;
    slots.water = true;
    return slots;
}

bool Near(float a, float b, float tolerance = 1e-4f) { return std::fabs(a - b) <= tolerance; }

// One row of a hand-built DXBC blob: the resources a shader declares, in the shape the engine's effect compiler writes them.
struct BindSpec
{
    const char* name;
    uint32_t type; // D3D_SIT_*: 0 is a constant buffer, 2 a texture, 3 a sampler state
    uint32_t bindPoint;
};

// A DXBC container carrying one RDEF chunk with those bindings, laid out the way ext/ffxiv/diag/ShaderBindings.h documents it. The engine's own
// reflection cannot be copied into a public repository, and the effect compiler's `name.T` suffix cannot be produced by fxc, so the suffix case is
// checked on a blob this test builds.
std::vector<uint8_t> RdefBlob(const std::vector<BindSpec>& binds)
{
    const uint32_t tableAt = 16;
    uint32_t namesAt = tableAt + uint32_t(binds.size()) * 32;
    std::vector<uint8_t> names;
    std::vector<uint32_t> nameAt;
    for (const BindSpec& bind : binds)
    {
        nameAt.push_back(namesAt + uint32_t(names.size()));
        for (const char* c = bind.name; *c != '\0'; ++c)
            names.push_back(uint8_t(*c));
        names.push_back(0);
    }
    const uint32_t bodySize = namesAt + uint32_t(names.size());
    std::vector<uint8_t> blob(44 + bodySize, 0);
    const auto put = [&blob](size_t at, uint32_t value) {
        for (int byte = 0; byte < 4; ++byte)
            blob[at + size_t(byte)] = uint8_t((value >> (8 * byte)) & 0xFFu);
    };
    std::memcpy(blob.data(), "DXBC", 4);
    put(20, 1);                          // version
    put(24, uint32_t(blob.size()));      // container size
    put(28, 1);                          // one chunk
    put(32, 36);                         // its offset
    std::memcpy(blob.data() + 36, "RDEF", 4);
    put(40, bodySize);
    const size_t body = 44;
    put(body + 0, 0); // no constant-buffer table: the bindings carry their own slots
    put(body + 4, 0);
    put(body + 8, uint32_t(binds.size()));
    put(body + 12, tableAt);
    for (size_t i = 0; i < binds.size(); ++i)
    {
        const size_t entry = body + tableAt + i * 32;
        put(entry + 0, nameAt[i]);
        put(entry + 4, binds[i].type);
        put(entry + 20, binds[i].bindPoint);
        put(entry + 24, 1);
    }
    std::memcpy(blob.data() + body + namesAt, names.data(), names.size());
    return blob;
}

// Whether a compiled blob contains a name as a byte string: the cheap scan that drops every shader which cannot be a sampler of the planar map.
bool Mentions(const void* code, size_t size, const char* name)
{
    const size_t length = std::strlen(name);
    const auto* bytes = static_cast<const uint8_t*>(code);
    for (size_t i = 0; i + length <= size; ++i)
        if (std::memcmp(bytes + i, name, length) == 0)
            return true;
    return false;
}
