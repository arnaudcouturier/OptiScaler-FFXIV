"""Generates the pure-virtual stubs of the fake ReShade device and effect runtime (fake_device_stubs.inc, fake_runtime_stubs.inc) from the
vendored headers, so tests/ext/reshade/reshade_depth_raw.cpp can derive from reshade::api::device and effect_runtime and implement by hand
only what it records. Every other method reports itself through Unexpected(name) and returns a zero value.

Run from the repository root:  python tests/ext/reshade/gen_fake_reshade_stubs.py
A vendored header update that adds a virtual function shows up as a compile error in the test (abstract class): run this again.
"""
import re
import pathlib

root = pathlib.Path(__file__).resolve().parents[3]
hdr = root / "OptiScaler" / "ext" / "reshade" / "third_party" / "reshade"
out = pathlib.Path(__file__).resolve().parent

DEVICE_BY_HAND = {"get_api", "get_native", "get_resource_desc"}
RUNTIME_BY_HAND = {
    "get_device", "get_native", "get_back_buffer_count", "get_back_buffer", "enumerate_texture_variables", "enumerate_uniform_variables",
    "enumerate_techniques", "get_texture_variable_name", "get_annotation_string_from_uniform_variable", "get_technique_effect_name",
    "get_preprocessor_definition", "get_preprocessor_definition_for_effect", "get_technique_state", "get_texture_binding",
    "update_texture_bindings", "get_uniform_value_bool", "set_uniform_value_bool",
}

decl = re.compile(r"^\s*virtual\s+(?P<ret>.*?)(?P<name>\w+)\s*\((?P<args>.*)\)\s*(?P<const>const)?\s*=\s*0;\s*$")


def section(path, start_pat, end_pat):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    begin = next(i for i, l in enumerate(lines) if re.search(start_pat, l))
    end = next((i for i, l in enumerate(lines) if i > begin and re.search(end_pat, l)), len(lines))
    return lines[begin:end]


def stubs(lines, skip):
    result = []
    seen = set()
    for l in lines:
        if l.strip().startswith("///"):
            continue
        m = decl.match(l)
        if not m:
            continue
        name = m.group("name")
        if name in skip or name in seen:
            continue
        seen.add(name)
        ret = m.group("ret").strip()
        args = re.sub(r"\s*=\s*(\{[^}]*\}|[^,)]+)", "", m.group("args"))
        const = " const" if m.group("const") else ""
        body = "{ Unexpected(\"%s\"); }" % name if ret == "void" else "{ Unexpected(\"%s\"); return {}; }" % name
        result.append("%s %s(%s)%s override %s" % (ret, name, args, const, body))
    return result


dev = hdr / "reshade_api_device.hpp"
api_object = section(dev, r"struct __declspec\(novtable\) api_object", r"struct __declspec\(novtable\) device\b")
device = section(dev, r"struct __declspec\(novtable\) device\b", r"struct __declspec\(novtable\) device_object")
device_object = section(dev, r"struct __declspec\(novtable\) device_object", r"struct __declspec\(novtable\) command_list")
runtime = section(hdr / "reshade_api.hpp", r"struct __declspec\(novtable\) effect_runtime", r"\Z-never-matches")

banner = "// GENERATED by gen_fake_reshade_stubs.py from the vendored ReShade headers. Do not edit.\n#pragma warning(push)\n#pragma warning(disable : 4100 4458)\n"
(out / "fake_device_stubs.inc").write_text(banner + "\n".join(stubs(api_object + device, DEVICE_BY_HAND)) + "\n#pragma warning(pop)\n", encoding="utf-8")
(out / "fake_runtime_stubs.inc").write_text(banner + "\n".join(stubs(api_object + device_object + runtime, RUNTIME_BY_HAND)) + "\n#pragma warning(pop)\n", encoding="utf-8")
print("device stubs:", len(stubs(api_object + device, DEVICE_BY_HAND)), "runtime stubs:", len(stubs(api_object + device_object + runtime, RUNTIME_BY_HAND)))
