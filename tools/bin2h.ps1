<#
  Converts a binary file to a C header array. Used by the ExtShader target in OptiScaler\ext\ext.props.
  Windows PowerShell 5.1 compatible.
#>
param(
    [Parameter(Mandatory)][string]$In,
    [Parameter(Mandatory)][string]$Out,
    [Parameter(Mandatory)][string]$Name
)
$bytes = [System.IO.File]::ReadAllBytes($In)
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("#pragma once`n`n// Generated by tools/bin2h.ps1 from $([System.IO.Path]::GetFileName($In)). Do not edit or commit.`n")
[void]$sb.Append("inline constexpr unsigned char $Name[] = {`n    ")
for ($i = 0; $i -lt $bytes.Length; $i++) {
    [void]$sb.Append('0x' + $bytes[$i].ToString('x2'))
    if ($i -lt $bytes.Length - 1) { [void]$sb.Append(', ') }
    if (($i + 1) % 16 -eq 0 -and $i -lt $bytes.Length - 1) { [void]$sb.Append("`n    ") }
}
[void]$sb.Append("`n};`n")
$text = $sb.ToString()
# keep the timestamp when nothing changed so MSBuild does not rebuild consumers
if (-not (Test-Path $Out) -or [System.IO.File]::ReadAllText($Out) -ne $text) {
    [System.IO.File]::WriteAllText($Out, $text, (New-Object System.Text.UTF8Encoding($false)))
}
