<#
  Converts a binary file to a C header array. Used by the ExtShader target in OptiScaler\ext\ext.props.
  Windows PowerShell 5.1 compatible.
#>
param(
    [Parameter(Mandatory)][string]$In,
    [Parameter(Mandatory)][string]$Out,
    [Parameter(Mandatory)][string]$Name,
    # Text mode (ExtShader Compiler=text): the file is an ASCII source string. The array is `char`, NUL terminated, so
    # sizeof(Name) matches the old R"(...)" literal and the text is handed to D3DCompile at run time.
    [switch]$Text
)
$bytes = [System.IO.File]::ReadAllBytes($In)
$type = 'unsigned char'
if ($Text) {
    foreach ($b in $bytes) { if ($b -gt 127) { Write-Error "$In is not ASCII"; exit 1 } }
    # The source text must not depend on the checkout's line endings (autocrlf): CRLF -> LF, like a raw string literal.
    $bytes = [byte[]]@($bytes | Where-Object { $_ -ne 13 })
    $bytes = $bytes + [byte]0
    $type = 'char'
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("#pragma once`n`n// Generated by tools/bin2h.ps1 from $([System.IO.Path]::GetFileName($In)). Do not edit or commit.`n")
[void]$sb.Append("inline constexpr $type $Name[] = {`n    ")
for ($i = 0; $i -lt $bytes.Length; $i++) {
    [void]$sb.Append('0x' + $bytes[$i].ToString('x2'))
    if ($i -lt $bytes.Length - 1) { [void]$sb.Append(', ') }
    if (($i + 1) % 16 -eq 0 -and $i -lt $bytes.Length - 1) { [void]$sb.Append("`n    ") }
}
[void]$sb.Append("`n};`n")
$content = $sb.ToString()
# keep the timestamp when nothing changed so MSBuild does not rebuild consumers
if (-not (Test-Path $Out) -or [System.IO.File]::ReadAllText($Out) -ne $content) {
    [System.IO.File]::WriteAllText($Out, $content, (New-Object System.Text.UTF8Encoding($false)))
}
